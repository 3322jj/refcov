def square(lon0, lat0, size=0.001):
    return [[lon0, lat0], [lon0 + size, lat0], [lon0 + size, lat0 + size], [lon0, lat0 + size], [lon0, lat0]]


def feature(props, polygons):
    """polygons：每个多边形是一个环的列表。"""
    return {"type": "Feature", "properties": props, "geometry": {"type": "MultiPolygon", "coordinates": polygons}}


FEATURES = [
    feature({"objectid": "1", "feature_code": "2100", "height_roof": "26.5", "name": None, "shape_area": "1000.5"},
            [[square(-73.78, 40.76)]]),
    feature({"objectid": "2", "feature_code": "5110", "height_roof": "0", "name": None, "shape_area": "300"},
            [[square(-73.77, 40.76)]]),
    feature({"objectid": "3", "feature_code": "2100", "height_roof": "0", "name": None, "shape_area": "50.25"},
            [[square(-73.765, 40.755)], [square(-73.7649, 40.7551, 0.0001)]]),
]


def geojson(features=FEATURES, crs=CRS84) -> bytes:
    doc = {"type": "FeatureCollection", "crs": {"type": "name", "properties": {"name": crs}}, "features": features}
    return json.dumps(doc).encode("utf-8")


GEOJSON = geojson()


def manifest(data: bytes = GEOJSON, dictionary: str = DICT) -> str:
    return build.build_manifest(data, dictionary.encode("utf-8"), URL)


def section_of(text: str, unit_id: str) -> str:
    start = text.index(f"## {unit_id}\n")
    end = text.find("\n\n## ", start)
    return text[start:] if end == -1 else text[start:end]


def test_units_are_crs_extent_then_fields_in_dictionary_order():
    """清单结构（设计第 3 节）：单元依次是 crs、extent，然后字段按字典顺序；SHAPE 是几何，不是字段。"""
    text = manifest()
    ids = [u.id for u in adapter.split(text.encode("utf-8"), "bayside.fields.md")]
    assert ids == ["crs", "extent", "objectid", "feature_code", "height_roof", "name", "shape_area"]


def test_same_inputs_give_the_same_bytes():
    """确定性（设计第 7 节）：同样的输入，两次生成的字节相同。"""
    assert manifest().encode("utf-8") == manifest().encode("utf-8")


def test_feature_code_section_has_dictionary_text_and_top_values():
    """字段节（设计第 3 节）：字典名、形状文件名、类型；`<br>` 换成换行；前 5 个取值按条数排好。"""
    sec = section_of(manifest(), "feature_code")
    assert "字典名：FEATURE_CODE；形状文件名：FEAT_CODE；字典类型：number。" in sec
    assert "字典说明：Type of Building. List of values:\n1000 = Parking\n2100 = Building\n5110 = Garage" in sec
    assert "数据：非空 3 条；不同取值 2 个；值为 0 的条数 0。" in sec
    assert "- 2100：2\n- 5110：1" in sec


def test_field_with_only_nulls_has_zero_counts_and_no_values():
    """字段节（设计第 2.1 节）：全为 null 的字段写非空 0 条，没有取值行。"""
    sec = section_of(manifest(), "name")
    assert "数据：非空 0 条；不同取值 0 个；值为 0 的条数 0。" in sec
    assert "（没有非空值）" in sec
    assert "- " not in sec


def test_zero_counts_use_the_stats_rule():
    """字段节（设计第 5 节）：字符串 "0" 算零；零的条数写在数据行里。"""
    sec = section_of(manifest(), "height_roof")
    assert "数据：非空 3 条；不同取值 2 个；值为 0 的条数 2。" in sec
    assert "- 0：2\n- 26.5：1" in sec


def test_extent_has_bbox_counts_hashes_and_dictionary_only_names():
    """范围和数据来源（设计第 3 节）：经纬度六位小数，条数，GeoJSON 和字典的 sha256，字典有而数据没有的字段。"""
    sec = section_of(manifest(), "extent")
    assert "经度：最小 -73.780000，最大 -73.764000。" in sec
    assert "纬度：最小 40.755000，最大 40.761000。" in sec
    assert "条数：3。" in sec
    assert f"GeoJSON 的 sha256：{hashlib.sha256(GEOJSON).hexdigest()}。" in sec
    assert f"字典的 sha256：{hashlib.sha256(DICT.encode('utf-8')).hexdigest()}。" in sec
    assert "字典里有、数据里没有的字段：GLOBALID、Length / Shape__Length / SHAPE_LENGTH / shape_length。" in sec


def test_crs_section_quotes_the_dictionary_rows_about_geometry_and_area():
    """坐标系（设计第 3 节）：几何类型计数，CRS84，字典 SHAPE 行和 Area 行的原文。"""
    sec = section_of(manifest(), "crs")
    assert "几何类型：MultiPolygon 3 个。" in sec
    assert f"坐标系：{CRS84}（经度在前，纬度在后）。" in sec
    assert "字典 Area 行原文（不得使用）：Do not use. This value is auto-generated by the system" in sec


def test_adapter_facts_agree_with_the_statistics():
    """一致性（设计第 4、5 节）：适配器从清单读回的数字，和统计函数算出的数字相同。"""
    text = manifest()
    got = adapter.facts(text.encode("utf-8"), "bayside.fields.md", "height_roof")
    st = stats.stats_of(["26.5", "0", "0"])
    assert (got["non_null"], got["distinct"], got["zeros"]) == (st.non_null, st.distinct, st.zeros)


def test_a_field_missing_from_the_dictionary_gets_a_unit_that_says_so():
    """字典里没有的字段（需求 2.3）：照样生成字段单元，明确写'字典里没有'，不静默省略。"""
    extra = [feature({**FEATURES[0]["properties"], "mystery": "x"}, [[square(-73.78, 40.76)]])]
    text = manifest(geojson(extra))
    assert "mystery" in [u.id for u in adapter.split(text.encode("utf-8"), "bayside.fields.md")]
    sec = section_of(text, "mystery")
    assert "字典里没有：" in sec
    assert "数据：非空 1 条；不同取值 1 个；值为 0 的条数 0。" in sec


def test_crs_quotes_the_horizontal_system_accuracy_and_length_rows():
    """坐标系（需求 3.1、3.3）：写明水平坐标系（EPSG:2263 的说明）、定位精度，以及 SHAPE_LENGTH 的不得使用行。"""
    sec = section_of(manifest(), "crs")
    assert "字典的水平坐标系（数据质量节原文）：New York State Plane Coordinates, Long Island East Zone, NAD83, US foot" in sec
    assert "字典的定位精度（数据质量节原文）：Estimated positional accuracy" in sec
    assert "字典 Length 行原文（不得使用）：Do not use." in sec


def test_extent_quotes_the_spatial_coverage_row():
    """范围（需求 3.2）：写明数据覆盖纽约市，取字典数据质量节的原文。"""
    sec = section_of(manifest(), "extent")
