def test_missing_data_quality_row_is_an_error():
    """对不上（需求 3.2）：字典里没有 Spatial Coverage 那一行，报错，不编一个覆盖范围。"""
    bad = DICT.replace("**Spatial Coverage** |New York City, NY\n", "")
    with pytest.raises(build.BuildError, match="Spatial Coverage"):
        manifest(dictionary=bad)


def test_quality_rows_are_read_with_or_without_leading_pipes():
    """字典的数据质量表（需求 3.2）：'**标签** |内容' 和 '| **标签** | 内容 |' 两种写法读出的内容相同。"""
    plain = "**Spatial Coverage** |New York City, NY\n"
    piped = "| **Spatial Coverage** | New York City, NY |\n"
    assert build.quality_value(plain, "Spatial Coverage") == "New York City, NY"
    assert build.quality_value(piped, "Spatial Coverage") == "New York City, NY"


def test_crlf_dictionary_gives_the_same_units_and_sections():
    """换行（原字典文件是 CRLF）：CRLF 的字典和 LF 的字典，各字段节和坐标系节的内容相同。"""
    crlf = manifest(dictionary=DICT.replace("\n", "\r\n"))
    lf = manifest()
    for unit_id in ("crs", "feature_code", "name", "shape_area"):
        assert section_of(crlf, unit_id) == section_of(lf, unit_id)


def test_crs_must_be_crs84():
    """对不上（设计第 7 节）：坐标系不是 CRS84 就报错。"""
    with pytest.raises(build.BuildError, match="CRS84"):
        manifest(geojson(crs="urn:ogc:def:crs:EPSG::2263"))


def test_geometry_must_be_multipolygon():
    """对不上（设计第 7 节）：几何不是 MultiPolygon 就报错。"""
    poly = {"type": "Feature", "properties": FEATURES[0]["properties"],
            "geometry": {"type": "Polygon", "coordinates": [square(-73.78, 40.76)]}}
    with pytest.raises(build.BuildError, match="MultiPolygon"):
        manifest(geojson([poly]))


def test_dictionary_without_an_attribute_table_is_an_error():
    """对不上（设计第 7 节）：字典里找不到 Attribute 表就报错。"""
    with pytest.raises(build.BuildError, match="Attribute"):
        manifest(dictionary="# no table here\n")


def test_dictionary_text_that_would_start_a_heading_is_refused():
    """拒绝（设计第 7 节）：字典文字里有以 # 开头的行，会被适配器当成标题，所以拒绝。"""
    bad = DICT.replace("Type of Building. List of values:<br>", "Type of Building.<br># heading<br>")
    with pytest.raises(build.BuildError, match="#"):
        manifest(dictionary=bad)


def test_a_value_with_a_newline_is_refused():
    """拒绝（设计第 3 节）：取值里有换行，清单一行写不下，报错。"""
    bad = [feature({**FEATURES[0]["properties"], "feature_code": "2100\nX"}, [[square(-73.78, 40.76)]])]
    with pytest.raises(build.BuildError, match="换行"):
        manifest(geojson(bad))


def test_no_coordinates_and_malformed_features_are_errors():
    """对不上（设计第 7 节）：没有坐标、要素格式不对，都报错，不抛出裸的异常。"""
    empty = [feature(FEATURES[0]["properties"], [])]
    with pytest.raises(build.BuildError, match="坐标"):
        manifest(geojson(empty))
    with pytest.raises(build.BuildError):
        manifest(geojson(["not a feature"]))


def test_non_utf8_geojson_is_an_error():
    """对不上（设计第 7 节）：GeoJSON 不是 UTF-8 就报错。"""
    with pytest.raises(build.BuildError):
        manifest(b"\xff\xfe")


def test_main_writes_the_manifest_and_a_failure_writes_nothing(tmp_path, monkeypatch):
    """命令行（设计第 7 节）：成功时写出的字节和 build_manifest 相同，返回 0；失败时返回 1，不写文件。"""
    monkeypatch.setattr(build, "fetch_dictionary", lambda url, timeout=60: DICT.encode("utf-8"))
    good = tmp_path / "good.geojson"
    good.write_bytes(GEOJSON)
    out = tmp_path / "out" / "bayside.fields.md"
    assert build.main(["--geojson", str(good), "--dictionary-url", URL, "--out", str(out)]) == 0
    assert out.read_bytes() == manifest().encode("utf-8")

    bad = tmp_path / "bad.geojson"
    bad.write_bytes(geojson(crs="EPSG:2263"))
    bad_out = tmp_path / "bad.md"
    assert build.main(["--geojson", str(bad), "--dictionary-url", URL, "--out", str(bad_out)]) == 1
    assert not bad_out.exists()


def test_main_returns_1_when_the_dictionary_cannot_be_read(tmp_path, monkeypatch):
    """命令行（设计第 7 节）：读不了字典网址时返回 1，不写文件。"""

    def offline(url, timeout=60):
        raise OSError("no network in this test")

    monkeypatch.setattr(build, "fetch_dictionary", offline)
    good = tmp_path / "good.geojson"
    good.write_bytes(GEOJSON)
    out = tmp_path / "bayside.fields.md"
    assert build.main(["--geojson", str(good), "--dictionary-url", URL, "--out", str(out)]) == 1
    assert not out.exists()
