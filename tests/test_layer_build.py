"""清单生成的测试（设计第 2.1、3、7 节）：假的 GeoJSON 和假的字典表。

输出字节相同；数据和字典对不上就失败且不写文件；清单里的数字和适配器读回的一致。
"""

import hashlib
import importlib.util
import json
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
_spec = importlib.util.spec_from_file_location("layer_build", ROOT / "apps" / "layer-coverage" / "build.py")
build = importlib.util.module_from_spec(_spec)
sys.modules["layer_build"] = build  # 同 test_layer_stats.py：dataclass 需要从 sys.modules 找回模块
_spec.loader.exec_module(build)
adapter = build.layer_adapter
stats = build.stats

URL = "https://example.invalid/Metadata_BuildingFootprints.md"
CRS84 = "urn:ogc:def:crs:OGC:1.3:CRS84"

# 字典的 Attribute 表（格式照原表：5 列，<br> 分隔别名，表头后有分隔行）
DICT = """# NYC Building Footprints

Some intro.

| Attribute | Shapefile Attribute | Description | Field Type | Notes | 
|------------ | ------------- | -------- | ----------- | ----------|
| OBJECTID | OBJECTID | Synthetic key populated by internal software | number | Use DOITT_ID instead for a consistent key identifying a building. |
| FEATURE_CODE | FEAT_CODE | Type of Building. List of values:<br>1000 = Parking<br>2100 = Building<br>5110 = Garage<br> | number | |
| GLOBALID | GLOBALID | A universally unique identifier | number | not published in all datasets |
| HEIGHT_ROOF | HEIGHTROOF | Roof height above ground elevation, in feet (not above sea level). | number | Records where this is zero or NULL mean that this information was not available. |
| NAME | NAME | Building name (limited to commonly known names). | text | |
| SHAPE | SHAPE | Building outline as a single outer polygon ring collected in [New York Long Island State Plane](https://spatialreference.org/ref/epsg/2263/) and published in [Web Mercator](https://spatialreference.org/ref/epsg/3857/). | varies | |
| Area <br> Shape__Area <br> SHAPE_AREA <br> shape_area | varies | Do not use. This value is auto-generated by the system in [Web Mercator](https://spatialreference.org/ref/epsg/3857/) which is not area preserving. | number | Do not use |

Some outro.
"""


def square(lon0, lat0, size=0.001):
    return [[lon0, lat0], [lon0 + size, lat0], [lon0 + size, lat0 + size], [lon0, lat0 + size], [lon0, lat0]]


def feature(props, polygons):
    """polygons：每个多边形是一个环的列表。"""
    return {"type": "Feature", "properties": props, "geometry": {"type": "MultiPolygon", "coordinates": polygons}}


FEATURES = [
    feature({"objectid": "1", "feature_code": "2100", "height_roof": "26.5", "name": None, "shape_area": "1000.5"},
            [[square(-73.78, 40.76)]]),
    feature({"objectid": "2", "feature_code": "5110", "height_roof": "0", "name": None, "shape_area": "300"},
            [[square(-73.77, 40.76)]]),
    feature({"objectid": "3", "feature_code": "2100", "height_roof": "0", "name": None, "shape_area": "50.25"},
            [[square(-73.765, 40.755)], [square(-73.7649, 40.7551, 0.0001)]]),
]


def geojson(features=FEATURES, crs=CRS84) -> bytes:
    doc = {"type": "FeatureCollection", "crs": {"type": "name", "properties": {"name": crs}}, "features": features}
    return json.dumps(doc).encode("utf-8")


GEOJSON = geojson()


def manifest(data: bytes = GEOJSON, dictionary: str = DICT) -> str:
    return build.build_manifest(data, dictionary.encode("utf-8"), URL)


def section_of(text: str, unit_id: str) -> str:
    start = text.index(f"## {unit_id}\n")
    end = text.find("\n\n## ", start)
    return text[start:] if end == -1 else text[start:end]


def test_units_are_crs_extent_then_fields_in_dictionary_order():
    """清单结构（设计第 3 节）：单元依次是 crs、extent，然后字段按字典顺序；SHAPE 是几何，不是字段。"""
    text = manifest()
    ids = [u.id for u in adapter.split(text.encode("utf-8"), "bayside.fields.md")]
    assert ids == ["crs", "extent", "objectid", "feature_code", "height_roof", "name", "shape_area"]


def test_same_inputs_give_the_same_bytes():
    """确定性（设计第 7 节）：同样的输入，两次生成的字节相同。"""
    assert manifest().encode("utf-8") == manifest().encode("utf-8")


def test_feature_code_section_has_dictionary_text_and_top_values():
    """字段节（设计第 3 节）：字典名、形状文件名、类型；`<br>` 换成换行；前 5 个取值按条数排好。"""
    sec = section_of(manifest(), "feature_code")
    assert "字典名：FEATURE_CODE；形状文件名：FEAT_CODE；字典类型：number。" in sec
    assert "字典说明：Type of Building. List of values:\n1000 = Parking\n2100 = Building\n5110 = Garage" in sec
    assert "数据：非空 3 条；不同取值 2 个；值为 0 的条数 0。" in sec
    assert "- 2100：2\n- 5110：1" in sec


def test_field_with_only_nulls_has_zero_counts_and_no_values():
    """字段节（设计第 2.1 节）：全为 null 的字段写非空 0 条，没有取值行。"""
    sec = section_of(manifest(), "name")
    assert "数据：非空 0 条；不同取值 0 个；值为 0 的条数 0。" in sec
    assert "（没有非空值）" in sec
    assert "- " not in sec


def test_zero_counts_use_the_stats_rule():
    """字段节（设计第 5 节）：字符串 "0" 算零；零的条数写在数据行里。"""
    sec = section_of(manifest(), "height_roof")
    assert "数据：非空 3 条；不同取值 2 个；值为 0 的条数 2。" in sec
    assert "- 0：2\n- 26.5：1" in sec


def test_extent_has_bbox_counts_hashes_and_dictionary_only_names():
    """范围和数据来源（设计第 3 节）：经纬度六位小数，条数，GeoJSON 和字典的 sha256，字典有而数据没有的字段。"""
    sec = section_of(manifest(), "extent")
    assert "经度：最小 -73.780000，最大 -73.764000。" in sec
    assert "纬度：最小 40.755000，最大 40.761000。" in sec
    assert "条数：3。" in sec
    assert f"GeoJSON 的 sha256：{hashlib.sha256(GEOJSON).hexdigest()}。" in sec
    assert f"字典的 sha256：{hashlib.sha256(DICT.encode('utf-8')).hexdigest()}。" in sec
    assert "字典里有、数据里没有的字段：GLOBALID。" in sec


def test_crs_section_quotes_the_dictionary_rows_about_geometry_and_area():
    """坐标系（设计第 3 节）：几何类型计数，CRS84，字典 SHAPE 行和 Area 行的原文。"""
    sec = section_of(manifest(), "crs")
    assert "几何类型：MultiPolygon 3 个。" in sec
    assert f"坐标系：{CRS84}（经度在前，纬度在后）。" in sec
    assert "字典 Area 行原文：Do not use. This value is auto-generated by the system" in sec


def test_adapter_facts_agree_with_the_statistics():
    """一致性（设计第 4、5 节）：适配器从清单读回的数字，和统计函数算出的数字相同。"""
    text = manifest()
    got = adapter.facts(text.encode("utf-8"), "bayside.fields.md", "height_roof")
    st = stats.stats_of(["26.5", "0", "0"])
    assert (got["non_null"], got["distinct"], got["zeros"]) == (st.non_null, st.distinct, st.zeros)


def test_key_missing_from_the_dictionary_is_an_error():
    """对不上（设计第 2.1 节）：数据里有字典没有的字段，报错并列出名字。"""
    extra = [feature({**FEATURES[0]["properties"], "mystery": "x"}, [[square(-73.78, 40.76)]])]
    with pytest.raises(build.BuildError, match="mystery"):
        manifest(geojson(extra))


def test_crs_must_be_crs84():
    """对不上（设计第 7 节）：坐标系不是 CRS84 就报错。"""
    with pytest.raises(build.BuildError, match="CRS84"):
        manifest(geojson(crs="urn:ogc:def:crs:EPSG::2263"))


def test_geometry_must_be_multipolygon():
    """对不上（设计第 7 节）：几何不是 MultiPolygon 就报错。"""
    poly = {"type": "Feature", "properties": FEATURES[0]["properties"],
            "geometry": {"type": "Polygon", "coordinates": [square(-73.78, 40.76)]}}
    with pytest.raises(build.BuildError, match="MultiPolygon"):
        manifest(geojson([poly]))


def test_dictionary_without_an_attribute_table_is_an_error():
    """对不上（设计第 7 节）：字典里找不到 Attribute 表就报错。"""
    with pytest.raises(build.BuildError, match="Attribute"):
        manifest(dictionary="# no table here\n")


def test_dictionary_text_that_would_start_a_heading_is_refused():
    """拒绝（设计第 7 节）：字典文字里有以 # 开头的行，会被适配器当成标题，所以拒绝。"""
    bad = DICT.replace("Type of Building. List of values:<br>", "Type of Building.<br># heading<br>")
    with pytest.raises(build.BuildError, match="#"):
        manifest(dictionary=bad)


def test_a_value_with_a_newline_is_refused():
    """拒绝（设计第 3 节）：取值里有换行，清单一行写不下，报错。"""
    bad = [feature({**FEATURES[0]["properties"], "feature_code": "2100\nX"}, [[square(-73.78, 40.76)]])]
    with pytest.raises(build.BuildError, match="换行"):
        manifest(geojson(bad))


def test_no_coordinates_and_malformed_features_are_errors():
    """对不上（设计第 7 节）：没有坐标、要素格式不对，都报错，不抛出裸的异常。"""
    empty = [feature(FEATURES[0]["properties"], [])]
    with pytest.raises(build.BuildError, match="坐标"):
        manifest(geojson(empty))
    with pytest.raises(build.BuildError):
        manifest(geojson(["not a feature"]))


def test_non_utf8_geojson_is_an_error():
    """对不上（设计第 7 节）：GeoJSON 不是 UTF-8 就报错。"""
    with pytest.raises(build.BuildError):
        manifest(b"\xff\xfe")


def test_main_writes_the_manifest_and_a_failure_writes_nothing(tmp_path, monkeypatch):
    """命令行（设计第 7 节）：成功时写出的字节和 build_manifest 相同，返回 0；失败时返回 1，不写文件。"""
    monkeypatch.setattr(build, "fetch_dictionary", lambda url, timeout=60: DICT.encode("utf-8"))
    good = tmp_path / "good.geojson"
    good.write_bytes(GEOJSON)
    out = tmp_path / "out" / "bayside.fields.md"
    assert build.main(["--geojson", str(good), "--dictionary-url", URL, "--out", str(out)]) == 0
    assert out.read_bytes() == manifest().encode("utf-8")

    bad = tmp_path / "bad.geojson"
    bad.write_bytes(geojson([feature({"mystery": "x"}, [[square(-73.78, 40.76)]])]))
    bad_out = tmp_path / "bad.md"
    assert build.main(["--geojson", str(bad), "--dictionary-url", URL, "--out", str(bad_out)]) == 1
    assert not bad_out.exists()


def test_main_returns_1_when_the_dictionary_cannot_be_read(tmp_path, monkeypatch):
    """命令行（设计第 7 节）：读不了字典网址时返回 1，不写文件。"""

    def offline(url, timeout=60):
        raise OSError("no network in this test")

    monkeypatch.setattr(build, "fetch_dictionary", offline)
    good = tmp_path / "good.geojson"
    good.write_bytes(GEOJSON)
    out = tmp_path / "bayside.fields.md"
    assert build.main(["--geojson", str(good), "--dictionary-url", URL, "--out", str(out)]) == 1
    assert not out.exists()
